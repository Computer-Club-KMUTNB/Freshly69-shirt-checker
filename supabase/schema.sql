-- Freshly69 shirt checker — database schema
-- Run this whole file once in Supabase → SQL Editor (safe to re-run: it only creates what is missing
-- and replaces the view/function).
--
-- Security model: the browser NEVER talks to Supabase. Every table has Row Level Security ON and
-- no policies, so the anon key can read nothing. Only the Next.js API routes (server side, using
-- SUPABASE_SERVICE_ROLE_KEY) can read/write.

-- One row per Google-Form response (a student can appear more than once — see issue_type).
create table if not exists students (
  id            bigint generated always as identity primary key,
  student_id    text        not null,           -- 13 digits, taken from the form e-mail
  title         text,                            -- นาย / นางสาว
  full_name     text        not null,
  form_faculty  text        not null,            -- which faculty's form (sheet) the response came from
  id_faculty    text,                            -- faculty inferred from the first 4 digits of student_id
  size          text        not null,            -- S, M, L, XL, 2XL ... 9XL (upper case)
  phone         text,                            -- as typed by the student (may be malformed)
  submitted_at  timestamptz,
  issue_type    text        not null default 'none'
                check (issue_type in ('none', 'dup_same', 'dup_size', 'dup_person'))
);
create index if not exists students_student_id_idx on students (student_id);

-- A shirt handed out. Undo = set voided_at (rows are never deleted, so history stays complete).
create table if not exists distributions (
  id              bigint generated always as identity primary key,
  student_id      text        not null,
  student_row_id  bigint      references students (id) on delete set null,
  size            text        not null,           -- size actually given
  faculty         text        not null,           -- faculty desk that handed it out
  device_id       text,
  device_name     text,
  created_at      timestamptz not null default now(),
  voided_at       timestamptz,
  void_device_id  text
);
-- At most ONE active (not voided) distribution per student: two phones scanning the same card at the
-- same moment cannot both succeed.
create unique index if not exists distributions_one_active_per_student
  on distributions (student_id) where voided_at is null;

create table if not exists devices (
  device_id   text primary key,                  -- random id generated by the browser on first unlock
  name        text,                              -- nickname typed at unlock (optional)
  role        text,
  user_agent  text,
  ip          text,
  first_seen  timestamptz not null default now(),
  last_seen   timestamptz not null default now()
);

create table if not exists logs (
  id           bigint generated always as identity primary key,
  at           timestamptz not null default now(),
  action       text not null,   -- unlock, unlock_fail, scan, search, confirm, void, view_pending, settings ...
  role         text,
  device_id    text,
  device_name  text,
  ip           text,
  user_agent   text,
  student_id   text,
  faculty      text,
  detail       jsonb
);
create index if not exists logs_at_idx on logs (at desc);
create index if not exists logs_student_idx on logs (student_id);

create table if not exists settings (
  key    text primary key,
  value  jsonb not null
);

create table if not exists login_attempts (
  id  bigint generated always as identity primary key,
  ip  text,
  at  timestamptz not null default now(),
  ok  boolean not null
);
create index if not exists login_attempts_ip_at_idx on login_attempts (ip, at desc);

alter table students       enable row level security;
alter table distributions  enable row level security;
alter table devices        enable row level security;
alter table logs           enable row level security;
alter table settings       enable row level security;
alter table login_attempts enable row level security;

-- One row per real person (student_id). For duplicates we keep the LATEST response and the faculty
-- inferred from the student id. Only freshmen (id starts with 69) count — others cannot receive a shirt.
create or replace view people with (security_invoker = true) as
select distinct on (student_id)
  student_id,
  title,
  coalesce(id_faculty, form_faculty) as faculty,
  size,
  case title when 'นาย' then 'M' when 'นางสาว' then 'F' else 'U' end as gender
from students
where student_id like '69%'
order by student_id, submitted_at desc nulls last;

-- All numbers for the overview page in one call (counts only, no names).
create or replace function get_stats() returns json
language sql stable security invoker as $$
with d as (
  select student_id, size, faculty, created_at from distributions where voided_at is null
), pp as (
  select p.*, (d.student_id is not null) as received
  from people p left join d using (student_id)
)
select json_build_object(
  'rows', (select coalesce(json_agg(r), '[]'::json) from (
            select faculty, gender, size, received, count(*)::int as n
            from pp group by 1, 2, 3, 4) r),
  'given_by_size', (select coalesce(json_agg(g), '[]'::json) from (
            select faculty, size, count(*)::int as n from d group by 1, 2) g),
  'hourly', (select coalesce(json_agg(h), '[]'::json) from (
            select to_char(created_at at time zone 'Asia/Bangkok', 'YYYY-MM-DD HH24') as hour,
                   count(*)::int as n
            from d group by 1 order by 1) h),
  'pending_scans', (select count(distinct l.student_id)::int from logs l
            where l.action in ('scan', 'search')
              and l.detail ->> 'result' in ('ok', 'dup_same', 'dup_size', 'dup_person')
              and not exists (select 1 from d where d.student_id = l.student_id)),
  'issues', (select coalesce(json_agg(i), '[]'::json) from (
            select s.issue_type,
                   count(distinct s.student_id)::int as n,
                   count(distinct s.student_id) filter (where d.student_id is not null)::int as resolved
            from students s left join d using (student_id)
            where s.issue_type <> 'none' and s.student_id like '69%' group by 1) i)
);
$$;

-- ADMIN ONLY (the API checks the role): people who have not received a shirt, with phone numbers.
create or replace function get_pending(p_faculty text default null) returns json
language sql stable security invoker as $$
select coalesce(json_agg(x order by x.faculty, x.student_id), '[]'::json) from (
  select distinct on (s.student_id)
    s.student_id, s.title, s.full_name, coalesce(s.id_faculty, s.form_faculty) as faculty,
    s.size, s.phone, s.issue_type
  from students s
  where s.student_id like '69%'
    and not exists (select 1 from distributions d where d.student_id = s.student_id and d.voided_at is null)
    and (p_faculty is null or coalesce(s.id_faculty, s.form_faculty) = p_faculty)
  order by s.student_id, s.submitted_at desc nulls last
) x;
$$;

revoke all on function get_stats() from public, anon, authenticated;
revoke all on function get_pending(text) from public, anon, authenticated;
revoke all on people from anon, authenticated;
